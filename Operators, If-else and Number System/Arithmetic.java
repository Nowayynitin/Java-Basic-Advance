public class Arithmetic {
    public static void main(String[] args) {
        int a = 80;
        int b = 2;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);

        double c = 3.14;
        double d = 6.66;
        System.out.println(c * d);
        System.out.println(c - d);
        System.out.println(c * d);
        System.out.println(c / d);


    }
}
